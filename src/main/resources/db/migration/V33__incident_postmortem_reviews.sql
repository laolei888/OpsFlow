CREATE TABLE IF NOT EXISTS incident_postmortems (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    incident_id BIGINT NOT NULL,
    review_no VARCHAR(32) NOT NULL,
    title VARCHAR(160) NOT NULL,
    status VARCHAR(24) NOT NULL,
    facilitator_id BIGINT NOT NULL,
    reviewer_id BIGINT NULL,
    executive_summary TEXT NULL,
    customer_impact TEXT NULL,
    root_cause TEXT NULL,
    contributing_factors TEXT NULL,
    detection_gap TEXT NULL,
    resolution_summary TEXT NULL,
    lessons_learned TEXT NULL,
    prevention_plan TEXT NULL,
    due_at DATETIME NULL,
    submitted_at DATETIME NULL,
    approved_at DATETIME NULL,
    published_at DATETIME NULL,
    review_comment VARCHAR(1000) NULL,
    rejected_reason VARCHAR(1000) NULL,
    created_by BIGINT NOT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    UNIQUE KEY uk_incident_postmortem_incident (tenant_id, incident_id),
    UNIQUE KEY uk_incident_postmortem_no (tenant_id, review_no),
    INDEX idx_incident_postmortem_status (tenant_id, status, updated_at),
    INDEX idx_incident_postmortem_reviewer (tenant_id, reviewer_id, status),
    INDEX idx_incident_postmortem_due (tenant_id, due_at, status)
);

CREATE TABLE IF NOT EXISTS incident_postmortem_actions (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    postmortem_id BIGINT NOT NULL,
    title VARCHAR(180) NOT NULL,
    description VARCHAR(2000) NULL,
    owner_id BIGINT NULL,
    priority VARCHAR(16) NOT NULL,
    status VARCHAR(24) NOT NULL,
    due_at DATETIME NULL,
    completion_evidence VARCHAR(2000) NULL,
    completed_at DATETIME NULL,
    created_by BIGINT NOT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    INDEX idx_postmortem_action_parent (tenant_id, postmortem_id, status),
    INDEX idx_postmortem_action_owner (tenant_id, owner_id, status, due_at)
);
