CREATE TABLE IF NOT EXISTS capacity_snapshots (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    captured_at DATETIME NOT NULL,
    capture_type VARCHAR(24) NOT NULL,
    label VARCHAR(120) NOT NULL,
    app_version VARCHAR(64) NOT NULL,
    release_id BIGINT NULL,
    active_users BIGINT NOT NULL DEFAULT 0,
    total_tickets BIGINT NOT NULL DEFAULT 0,
    active_tickets BIGINT NOT NULL DEFAULT 0,
    overdue_tickets BIGINT NOT NULL DEFAULT 0,
    tickets_created_24h BIGINT NOT NULL DEFAULT 0,
    tickets_resolved_24h BIGINT NOT NULL DEFAULT 0,
    published_articles BIGINT NOT NULL DEFAULT 0,
    active_assets BIGINT NOT NULL DEFAULT 0,
    active_incidents BIGINT NOT NULL DEFAULT 0,
    firing_alerts BIGINT NOT NULL DEFAULT 0,
    async_backlog BIGINT NOT NULL DEFAULT 0,
    attachment_backlog BIGINT NOT NULL DEFAULT 0,
    attachment_bytes BIGINT NOT NULL DEFAULT 0,
    database_bytes BIGINT NOT NULL DEFAULT 0,
    heap_used_bytes BIGINT NOT NULL DEFAULT 0,
    heap_max_bytes BIGINT NOT NULL DEFAULT 0,
    created_by BIGINT NULL,
    created_at DATETIME NOT NULL,
    INDEX idx_capacity_tenant_captured (tenant_id, captured_at, id),
    INDEX idx_capacity_tenant_version (tenant_id, app_version, captured_at),
    INDEX idx_capacity_release (tenant_id, release_id, captured_at)
);
