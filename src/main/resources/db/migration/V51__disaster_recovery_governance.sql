CREATE TABLE IF NOT EXISTS disaster_recovery_policies (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    rpo_minutes INT NOT NULL DEFAULT 60,
    rto_minutes INT NOT NULL DEFAULT 120,
    retention_days INT NOT NULL DEFAULT 30,
    verification_interval_hours INT NOT NULL DEFAULT 24,
    require_encryption BOOLEAN NOT NULL DEFAULT TRUE,
    require_immutable_copy BOOLEAN NOT NULL DEFAULT TRUE,
    require_cross_region_copy BOOLEAN NOT NULL DEFAULT FALSE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NOT NULL,
    updated_by BIGINT NOT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    UNIQUE KEY uk_dr_policy_tenant (tenant_id)
);

CREATE TABLE IF NOT EXISTS backup_snapshots (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    backup_no VARCHAR(32) NOT NULL,
    scope VARCHAR(32) NOT NULL,
    status VARCHAR(24) NOT NULL,
    storage_provider VARCHAR(64) NOT NULL,
    storage_location VARCHAR(500) NOT NULL,
    region VARCHAR(64) NOT NULL,
    recovery_point_at DATETIME NOT NULL,
    captured_at DATETIME NOT NULL,
    completed_at DATETIME NOT NULL,
    size_bytes BIGINT NOT NULL,
    checksum_sha256 CHAR(64) NOT NULL,
    encrypted BOOLEAN NOT NULL DEFAULT TRUE,
    immutable_until DATETIME NULL,
    cross_region_copy BOOLEAN NOT NULL DEFAULT FALSE,
    verification_status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    verification_detail VARCHAR(1000) NULL,
    verified_at DATETIME NULL,
    evidence_note VARCHAR(1000) NULL,
    created_by BIGINT NOT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    UNIQUE KEY uk_backup_snapshot_no (tenant_id, backup_no),
    INDEX idx_backup_snapshot_readiness (tenant_id, status, recovery_point_at),
    INDEX idx_backup_snapshot_verification (tenant_id, verification_status, verified_at)
);

CREATE TABLE IF NOT EXISTS recovery_drills (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    drill_no VARCHAR(32) NOT NULL,
    name VARCHAR(160) NOT NULL,
    backup_snapshot_id BIGINT NOT NULL,
    status VARCHAR(24) NOT NULL,
    version INT NOT NULL DEFAULT 0,
    environment VARCHAR(64) NOT NULL,
    scheduled_at DATETIME NULL,
    started_at DATETIME NULL,
    completed_at DATETIME NULL,
    target_rpo_minutes INT NOT NULL,
    target_rto_minutes INT NOT NULL,
    achieved_rpo_minutes INT NULL,
    achieved_rto_minutes INT NULL,
    integrity_score INT NULL,
    evidence_note VARCHAR(2000) NULL,
    findings VARCHAR(2000) NULL,
    failure_reason VARCHAR(1000) NULL,
    created_by BIGINT NOT NULL,
    started_by BIGINT NULL,
    completed_by BIGINT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    UNIQUE KEY uk_recovery_drill_no (tenant_id, drill_no),
    INDEX idx_recovery_drill_status (tenant_id, status, scheduled_at),
    CONSTRAINT fk_recovery_drill_snapshot FOREIGN KEY (backup_snapshot_id) REFERENCES backup_snapshots(id)
);

CREATE TABLE IF NOT EXISTS recovery_drill_checks (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    drill_id BIGINT NOT NULL,
    check_key VARCHAR(64) NOT NULL,
    label VARCHAR(160) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    required_check BOOLEAN NOT NULL DEFAULT TRUE,
    detail VARCHAR(1000) NULL,
    evidence VARCHAR(1000) NULL,
    sort_order INT NOT NULL DEFAULT 0,
    updated_by BIGINT NULL,
    checked_at DATETIME NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    UNIQUE KEY uk_recovery_drill_check (drill_id, check_key),
    INDEX idx_recovery_drill_check_status (tenant_id, drill_id, status),
    CONSTRAINT fk_recovery_drill_check_drill FOREIGN KEY (drill_id) REFERENCES recovery_drills(id)
);
