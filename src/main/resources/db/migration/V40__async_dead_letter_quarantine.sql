CREATE TABLE IF NOT EXISTS async_dead_letter_messages (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    outbox_event_id BIGINT NULL,
    message_id VARCHAR(100) NOT NULL,
    notification_type VARCHAR(32) NULL,
    title VARCHAR(160) NULL,
    recipient_id BIGINT NULL,
    dedupe_key VARCHAR(160) NULL,
    source_queue VARCHAR(160) NOT NULL,
    source_exchange VARCHAR(160) NULL,
    original_routing_key VARCHAR(160) NOT NULL,
    dead_letter_reason VARCHAR(80) NOT NULL,
    death_count BIGINT NOT NULL DEFAULT 1,
    payload_json LONGTEXT NOT NULL,
    headers_json LONGTEXT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'QUARANTINED',
    requeue_count INT NOT NULL DEFAULT 0,
    last_error VARCHAR(1000) NULL,
    resolution_note VARCHAR(500) NULL,
    quarantined_at DATETIME NOT NULL,
    requeue_started_at DATETIME NULL,
    last_requeued_at DATETIME NULL,
    resolved_at DATETIME NULL,
    updated_at DATETIME NOT NULL,
    UNIQUE KEY uk_async_dead_letter_message (tenant_id, message_id),
    INDEX idx_async_dead_letter_tenant_status (tenant_id, status, quarantined_at),
    INDEX idx_async_dead_letter_outbox (outbox_event_id)
);
