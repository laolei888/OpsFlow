CREATE TABLE IF NOT EXISTS attachment_upload_sessions (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    session_key CHAR(36) NOT NULL,
    client_upload_id VARCHAR(64) NOT NULL,
    tenant_id BIGINT NOT NULL,
    ticket_id BIGINT NOT NULL,
    uploader_id BIGINT NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    stored_name VARCHAR(128) NOT NULL,
    content_type VARCHAR(128) NOT NULL,
    size_bytes BIGINT NOT NULL,
    storage_backend VARCHAR(16) NOT NULL,
    storage_path VARCHAR(512) NOT NULL,
    provider_upload_id VARCHAR(1024) NOT NULL,
    status VARCHAR(24) NOT NULL,
    part_size BIGINT NOT NULL,
    total_parts INT NOT NULL,
    attachment_id BIGINT NULL,
    failure_reason VARCHAR(1000) NULL,
    expires_at DATETIME NOT NULL,
    completed_at DATETIME NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    UNIQUE KEY uk_attachment_upload_session (session_key),
    UNIQUE KEY uk_attachment_upload_client (tenant_id, uploader_id, client_upload_id),
    INDEX idx_attachment_upload_ticket (tenant_id, ticket_id, created_at),
    INDEX idx_attachment_upload_cleanup (status, expires_at, id)
);
