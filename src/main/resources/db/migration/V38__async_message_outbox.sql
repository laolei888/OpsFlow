CREATE TABLE IF NOT EXISTS async_message_outbox (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    recipient_id BIGINT NOT NULL,
    message_id CHAR(36) NOT NULL,
    event_type VARCHAR(80) NOT NULL,
    routing_key VARCHAR(120) NOT NULL,
    aggregate_type VARCHAR(80) NULL,
    aggregate_id BIGINT NULL,
    dedupe_key VARCHAR(160) NOT NULL,
    payload_json LONGTEXT NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    attempt_count INT NOT NULL DEFAULT 0,
    next_attempt_at DATETIME NOT NULL,
    claimed_at DATETIME NULL,
    published_at DATETIME NULL,
    last_error VARCHAR(1000) NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    UNIQUE KEY uk_async_message_id (message_id),
    UNIQUE KEY uk_async_notification_dedupe (tenant_id, recipient_id, dedupe_key),
    INDEX idx_async_message_due (status, next_attempt_at, id),
    INDEX idx_async_message_tenant_status (tenant_id, status, created_at)
);
