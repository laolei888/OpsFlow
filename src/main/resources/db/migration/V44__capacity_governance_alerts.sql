CREATE TABLE IF NOT EXISTS capacity_alerts (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    alert_no VARCHAR(32) NOT NULL,
    metric_key VARCHAR(64) NOT NULL,
    metric_label VARCHAR(80) NOT NULL,
    level VARCHAR(16) NOT NULL,
    status VARCHAR(20) NOT NULL,
    current_value BIGINT NOT NULL,
    threshold_value BIGINT NOT NULL,
    utilization_percent DECIMAL(8,2) NOT NULL,
    daily_growth DECIMAL(18,2) NOT NULL DEFAULT 0,
    projected_days BIGINT NULL,
    snapshot_id BIGINT NOT NULL,
    occurrence_count INT NOT NULL DEFAULT 1,
    first_detected_at DATETIME NOT NULL,
    last_detected_at DATETIME NOT NULL,
    acknowledged_by BIGINT NULL,
    acknowledged_at DATETIME NULL,
    acknowledgement_note VARCHAR(500) NULL,
    resolved_by BIGINT NULL,
    resolved_at DATETIME NULL,
    resolution_note VARCHAR(500) NULL,
    active_key VARCHAR(100) NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    UNIQUE KEY uk_capacity_alert_no (tenant_id, alert_no),
    UNIQUE KEY uk_capacity_alert_active (active_key),
    INDEX idx_capacity_alert_queue (tenant_id, status, level, updated_at),
    INDEX idx_capacity_alert_metric (tenant_id, metric_key, created_at),
    INDEX idx_capacity_alert_snapshot (tenant_id, snapshot_id)
);
